UUID_SERVICE_CMD = UUID("0000fff0-0000-1000-8000-00805f9b34fb")
UUID_CHAR_CMD_NOTIFY = UUID("0000fff1-0000-1000-8000-00805f9b34fb")
UUID_CHAR_CMD_WRITE = UUID("0000fff2-0000-1000-8000-00805f9b34fb")

# Shell / Pairing AT Service (0x77D4E67C)
UUID_SERVICE_SHELL = UUID("77d4e67c-2fe2-2334-0d35-9ccd078f529c")
UUID_CHAR_SHELL_WRITE = UUID("77d4ff01-2fe2-2334-0d35-9ccd078f529c")
UUID_CHAR_SHELL_NOTIFY = UUID("77d4ff02-2fe2-2334-0d35-9ccd078f529c")

# Bulk Data Transfer Service (0x02F00000...FFE0)
UUID_SERVICE_DATA = UUID("02f00000-0000-0000-0000-00000000ffe0")
UUID_CHAR_DATA_WRITE = UUID("02f00000-0000-0000-0000-00000000ffe1")
UUID_CHAR_DATA_NOTIFY = UUID("02f00000-0000-0000-0000-00000000ffe2")

# Standard Client Characteristic Configuration Descriptor
UUID_CCCD = UUID("00002902-0000-1000-8000-00805f9b34fb")

